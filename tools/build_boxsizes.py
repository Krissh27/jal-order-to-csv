#!/usr/bin/env python3
"""Build vendor/boxsizes.js: pieces per box for every code the app can look up.

    python3 tools/build_boxsizes.py path/to/Product_List_Detail_Report.xlsx

Inputs (edit these when box sizes change or new brands are added):
  data/ptmt_box_sizes.csv   box sizes per catalogue code (from the PTMT MOQ sheet)
  data/ptmt_box_types.csv   box sizes per product type ("All Bib Swivel ..." rows)
  the master product list   for each code's description, to work out its type

For each catalogue code, the box size comes from, in order:
  sheet   the code itself is on the box sheet
  colour  the same tap in another colour is on the sheet (PT12362-31 -> PT12362-26)
  type    a PTMT faucet whose description matches a product-type row (estimate)
Codes with none of these are left out; the app asks staff for the pieces.
"""
import csv, json, re, sys
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
SIZES = ROOT / "data" / "ptmt_box_sizes.csv"
TYPES = ROOT / "data" / "ptmt_box_types.csv"
OUT   = ROOT / "vendor" / "boxsizes.js"

def colour_base(code):
    """PT12362-31 -> PT12362 (a 2-digit colour suffix); other codes unchanged."""
    m = re.match(r"^(.+)-(\d{2})$", code)
    return m.group(1) if m else code

def type_of(desc):
    """Product-type row number for a PTMT faucet description, or None. Order matters."""
    d = desc.upper()
    two_way = "TWO WAY" in d or "2 WAY" in d
    if "WALL MIXER" in d:                       return 7
    if two_way and "ANGLE" in d:                return 4
    if "ANGLE" in d and "COCK" in d:            return 5
    if two_way and "BIB" in d:                  return 6
    if "SWIVEL" in d and ("BIB" in d or "PILLAR" in d): return 3
    if "PILLAR" in d:                           return 4
    if "BIB" in d and "LONG BODY" in d:         return 1
    if "BIB" in d:                              return 2
    return None

def main(master_xlsx):
    sheet = {r["code"].strip().upper(): r for r in csv.DictReader(open(SIZES, newline=""))}
    types = {int(r["type_no"]): r for r in csv.DictReader(open(TYPES, newline=""))}

    df = pd.read_excel(master_xlsx)
    df.columns = [str(c).strip() for c in df.columns]
    df = df.dropna(subset=["Pucode"])
    df["Pucode"] = df["Pucode"].astype(str).str.strip()
    df["Product"] = df["Product"].fillna("").astype(str)
    df["Group Chain"] = df["Group Chain"].fillna("").astype(str)

    by_base = {}
    for code in sheet:
        by_base.setdefault(colour_base(code), []).append(code)

    out, counts = {}, {"sheet": 0, "colour": 0, "type": 0}
    for _, r in df.iterrows():
        code = r["Pucode"]; up = code.upper()
        if up in sheet:
            s = sheet[up]; out[code] = [int(s["small_box_qty"]), int(s["master_box_qty"]), "sheet", ""]
            counts["sheet"] += 1; continue
        sibs = by_base.get(colour_base(up), [])
        if sibs and colour_base(up) != up:
            s = sheet[sibs[0]]; out[code] = [int(s["small_box_qty"]), int(s["master_box_qty"]), "colour", s["code"]]
            counts["colour"] += 1; continue
        if r["Group Chain"].split(">>")[-1].strip().upper() == "PTMT":
            t = type_of(r["Product"])
            if t:
                s = types[t]; out[code] = [int(s["small_box_qty"]), int(s["master_box_qty"]), "type", s["description"]]
                counts["type"] += 1

    # How well do the type rules agree with codes that ARE on the sheet?
    check = []
    for code, s in sheet.items():
        hit = df[df["Pucode"].str.upper() == code]
        if hit.empty: continue
        t = type_of(hit["Product"].iloc[0])
        if t: check.append((code, int(s["small_box_qty"]), int(types[t]["small_box_qty"])))
    agree = sum(1 for _, a, b in check if a == b)

    missing_from_master = [c for c in sheet if c not in set(df["Pucode"].str.upper())]

    OUT.write_text(
        "// Pieces per box for JAL order codes. Generated by tools/build_boxsizes.py — do not edit by hand.\n"
        "// Each entry: [small box qty, master box qty, source, reference]\n"
        "//   source 'sheet'  = on the PTMT MOQ sheet\n"
        "//   source 'colour' = same tap in another colour is on the sheet (reference = that code)\n"
        "//   source 'type'   = estimated from the product-type rows (reference = the type row)\n"
        "window.JAL_BOXSIZES = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)}: {len(out)} codes  {counts}")
    print(f"type rules vs sheet: {agree}/{len(check)} small-box sizes agree")
    for code, a, b in check:
        if a != b: print(f"   {code}: sheet {a}, type row {b}")
    if missing_from_master:
        print("on the box sheet but not in the product list:", ", ".join(missing_from_master))

if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
